import { buildDesignDigest } from "./generate-prompt-pro.mjs";
import { callAI } from "./ai-client.mjs";

/**
 * AI component code generation — turns the measured design DNA (and,
 * optionally, section screenshots for vision grounding) into real,
 * paste-ready component code, not just a prompt. The Locofy-killer:
 * Locofy starts from Figma, we start from the live site with exact
 * measured tokens.
 *
 * Providers: Groq / OpenAI / Claude / Kimi via lib/ai-client.mjs.
 */

const FRAMEWORK_INSTRUCTIONS = {
  react: "Output React function components in JSX with a companion CSS module or inline style objects. Use the measured tokens as CSS custom properties.",
  vue: "Output Vue 3 single-file components (<template>/<script setup>/<style scoped>).",
  html: "Output a single self-contained index.html with an embedded <style> block — no build step, opens directly in a browser."
};

export function buildCodeMessages({ digest, framework, screenshots }) {
  const frameworkLine = FRAMEWORK_INSTRUCTIONS[framework] || FRAMEWORK_INSTRUCTIONS.react;
  const system = [
    "You are a senior frontend engineer who reproduces designs pixel-faithfully.",
    "You receive the measured DESIGN DNA of a website (tokens, typography, spacing grid, components, layout, motion).",
    `Generate production-ready components that reproduce the site's look. ${frameworkLine}`,
    "Rules: use ONLY the measured token values — never invent colors, sizes, radii, or fonts. Reproduce the measured button variants, input, card, and heading hierarchy exactly. Include hover/focus-visible states. Keep it accessible (semantic HTML, visible focus). Structure the output as clearly separated files, each introduced by a `// FILE: <path>` comment line. Start with a tokens file, then components, then a small demo/preview. Output ONLY code and file markers — no prose explanation.",
    screenshots && screenshots.length > 0
      ? "The attached screenshots show the real composition — match the layout, proportions, and art direction you see, not just the numbers."
      : ""
  ].filter(Boolean).join("\n");

  const userMessage = {
    role: "user",
    text: ["=== DESIGN DNA (measured) ===", digest, "", "Generate the component code now."].join("\n")
  };
  if (screenshots && screenshots.length > 0) {
    userMessage.images = screenshots.slice(0, 4).map((base64) => ({ mediaType: "image/png", base64 }));
  }
  return [
    { role: "system", text: system },
    userMessage
  ];
}

/**
 * Splits an AI response containing `// FILE: path` markers into files.
 * Falls back to a single file when no markers are present.
 */
export function parseGeneratedFiles(content, framework) {
  const text = String(content || "").replace(/^```[a-z]*\n?|```$/gim, "");
  const marker = /(?:^|\n)\s*(?:\/\/|<!--|#)\s*FILE:\s*([^\n*]+?)\s*(?:-->)?\s*\n/gi;
  const files = [];
  const matches = [...text.matchAll(marker)];
  if (matches.length === 0) {
    const ext = framework === "vue" ? "vue" : framework === "html" ? "html" : "jsx";
    return [{ path: `generated-component.${ext}`, content: text.trim() + "\n" }];
  }
  for (let i = 0; i < matches.length; i++) {
    const path = matches[i][1].trim().replace(/[`"']/g, "").replace(/^\/+/, "");
    const start = matches[i].index + matches[i][0].length;
    const end = i + 1 < matches.length ? matches[i + 1].index : text.length;
    const body = text.slice(start, end).replace(/```[a-z]*\n?/gi, "").trim();
    if (path && body) {
      files.push({ path: `generated-code/${path}`, content: body + "\n" });
    }
  }
  return files.length > 0 ? files : [{ path: "generated-code/component.txt", content: text.trim() + "\n" }];
}

export async function generateComponentCode({ normalized, framework = "react", settings, screenshots, fetchImpl }) {
  const digest = buildDesignDigest(normalized);
  const messages = buildCodeMessages({ digest, framework, screenshots });
  const { content, model, provider } = await callAI({
    provider: settings.provider,
    apiKey: settings.apiKey,
    model: settings.model,
    baseUrl: settings.baseUrl,
    messages,
    maxTokens: 6000,
    fetchImpl
  });
  const files = parseGeneratedFiles(content, framework);
  const readme = [
    `# Generated components — ${framework}`,
    "",
    `Generated by Keys_Osi_Design.md-extractor (${provider}/${model}${screenshots?.length ? ", vision-grounded" : ""}) from ${normalized.source?.url || "the target site"}.`,
    "",
    "Every value is measured from the live site. Review before shipping — AI output is a strong starting point, not a final artifact.",
    ""
  ].join("\n");
  return {
    files: [{ path: "generated-code/README.md", content: readme }, ...files],
    provider,
    model
  };
}
