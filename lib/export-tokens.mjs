/**
 * Exports normalized extraction data as:
 *  - a W3C Design Tokens (Design Tokens Community Group) JSON document,
 *    compatible with Style Dictionary, Figma Tokens, etc.
 *  - a tailwind.config.js theme extension.
 */

export function generateW3cTokens(normalized) {
  const doc = {
    $schema: "https://design-tokens.github.io/community-group/format/",
    $description: `Design tokens extracted from ${normalized.source?.url || "unknown URL"} on ${normalized.sampledAt || "unknown date"}`,
    color: {},
    font: {},
    dimension: {},
    shadow: {},
    duration: {},
    gradient: {}
  };

  for (const row of normalized.colorPalette || []) {
    setNested(doc.color, tokenTail(row.token, "color"), {
      $type: "color",
      $value: rawValue(row.value)
    });
  }

  if (normalized.mainFontStyle?.familyStack) {
    doc.font.family = {
      primary: {
        $type: "fontFamily",
        $value: normalized.mainFontStyle.familyStack.split(",").map((part) => part.trim())
      }
    };
  }
  for (const row of normalized.typographyScale || []) {
    setNested(doc.font, tokenTail(row.token, "font"), {
      $type: "dimension",
      $value: rawValue(row.value)
    });
  }

  for (const row of normalized.spacingScale || []) {
    setNested(doc.dimension, tokenTail(row.token, ""), {
      $type: "dimension",
      $value: rawValue(row.value)
    });
  }
  for (const row of normalized.radiusTokens || []) {
    setNested(doc.dimension, tokenTail(row.token, ""), {
      $type: "dimension",
      $value: rawValue(row.value)
    });
  }

  for (const row of normalized.shadowTokens || []) {
    setNested(doc.shadow, tokenTail(row.token, "shadow"), {
      $type: "shadow",
      $value: rawValue(row.value)
    });
  }

  for (const row of normalized.motionDurationTokens || []) {
    setNested(doc.duration, tokenTail(row.token, "motion.duration"), {
      $type: "duration",
      $value: rawValue(row.value)
    });
  }

  for (const row of normalized.gradientTokens || []) {
    setNested(doc.gradient, tokenTail(row.token, "color.gradient"), {
      $type: "gradient",
      $value: rawValue(row.value)
    });
  }

  for (const key of Object.keys(doc)) {
    if (!key.startsWith("$") && Object.keys(doc[key]).length === 0) {
      delete doc[key];
    }
  }

  return doc;
}

export function generateTailwindConfig(normalized) {
  const colors = {};
  for (const row of normalized.colorPalette || []) {
    const name = tokenTail(row.token, "color").join("-");
    colors[name] = rawValue(row.value);
  }

  const spacing = {};
  (normalized.spacingScale || []).forEach((row, index) => {
    spacing[`site-${index + 1}`] = rawValue(row.value);
  });

  const borderRadius = {};
  for (const row of normalized.radiusTokens || []) {
    borderRadius[tokenTail(row.token, "radius").join("-")] = rawValue(row.value);
  }

  const boxShadow = {};
  (normalized.shadowTokens || []).forEach((row, index) => {
    boxShadow[`site-${index + 1}`] = rawValue(row.value);
  });

  const fontSize = {};
  for (const row of normalized.typographyScale || []) {
    fontSize[tokenTail(row.token, "font.size").join("-")] = rawValue(row.value);
  }

  const transitionDuration = {};
  for (const row of normalized.motionDurationTokens || []) {
    transitionDuration[tokenTail(row.token, "motion.duration").join("-")] = rawValue(row.value);
  }

  const screens = {};
  (normalized.breakpoints || []).forEach((item, index) => {
    const names = ["sm", "md", "lg", "xl", "2xl"];
    screens[names[index] || `bp${index + 1}`] = `${item.px}px`;
  });

  const fontFamily = normalized.mainFontStyle?.familyStack
    ? {
        sans: normalized.mainFontStyle.familyStack
          .split(",")
          .map((part) => part.trim())
      }
    : undefined;

  const theme = {
    extend: {
      colors,
      spacing,
      borderRadius,
      boxShadow,
      fontSize,
      transitionDuration,
      ...(fontFamily ? { fontFamily } : {}),
      ...(Object.keys(screens).length > 0 ? { screens } : {})
    }
  };

  const header = [
    "/**",
    ` * Tailwind theme extracted from ${normalized.source?.url || "unknown URL"}`,
    ` * Generated by Keys_Osi_Design.md-extractor on ${normalized.sampledAt || new Date().toISOString()}`,
    " */"
  ].join("\n");

  return `${header}\n/** @type {import('tailwindcss').Config} */\nmodule.exports = {\n  content: ["./src/**/*.{html,js,jsx,ts,tsx,vue,svelte}"],\n  theme: ${JSON.stringify(theme, null, 2).replace(/\n/g, "\n  ")}\n};\n`;
}

/** Strips a known prefix from a token name and returns path segments. */
function tokenTail(token, prefix) {
  const name = String(token || "");
  const stripped = prefix && name.startsWith(`${prefix}.`) ? name.slice(prefix.length + 1) : name;
  return stripped.split(".").filter(Boolean);
}

/** Removes the "(var(--x))" annotation appended during normalization. */
function rawValue(value) {
  return String(value || "").replace(/\s*\(var\(--[^)]*\)\)\s*$/, "").trim();
}

function setNested(target, segments, leaf) {
  let node = target;
  for (let i = 0; i < segments.length - 1; i++) {
    const key = segments[i];
    if (!node[key] || typeof node[key] !== "object" || node[key].$value !== undefined) {
      node[key] = {};
    }
    node = node[key];
  }
  node[segments[segments.length - 1] || "value"] = leaf;
}
