import {
  buildAtmosphereDescription,
  computeDesignScore,
  contrastRatioHex,
  estimateScaleRatio,
  inferSpacingBase,
  splitTokenValue
} from "./generate-design-md.mjs";

/**
 * PROMPT.md — a ready-to-paste master prompt for a coding agent.
 *
 * Everything in it is measured, not invented: the agent receives the
 * mission, the non-negotiable tokens, the section-by-section build
 * plan with the site's real content, exact component CSS, the motion
 * script, the responsive plan, and a definition of done. Designed to
 * be pasted alone, or alongside the companion files it references.
 */
export function generatePromptMarkdown(context) {
  const { normalized } = context;
  const name = inferName(normalized.source?.title);
  const url = normalized.source?.url || "the target site";
  const palette = normalized.colorPalette || [];
  const font = normalized.mainFontStyle || {};
  const stackNames = (normalized.stack || []).map((item) => item.name);
  const { score } = computeDesignScore(normalized);

  const lines = [];
  lines.push(`# PROMPT.md — Rebuild "${name}" pixel-faithfully`);
  lines.push("");
  lines.push(`> Generated by Keys_Osi_Design.md-extractor from live measurements of ${url}.`);
  lines.push("> Paste everything below this line into your coding agent.");
  lines.push("");
  lines.push("---");
  lines.push("");

  /* Role + mission */
  lines.push("You are a senior design engineer with an obsessive eye for fidelity. Your mission: rebuild the website described below **identically** — same atmosphere, same rhythm, same motion. Every value in this brief was measured on the live site; treat it as ground truth, never as inspiration.");
  lines.push("");
  lines.push(`**The site in one sentence:** ${buildAtmosphereDescription(normalized)}`);
  lines.push("");

  /* Stack */
  lines.push("## 1. Stack");
  if (stackNames.length > 0) {
    lines.push(`The source is built with: ${stackNames.join(", ")}. ${recommendStackLine(stackNames)}`);
  } else {
    lines.push("No framework detected on the source. Use semantic HTML + modern CSS (or the stack of your choice) — the tokens below are framework-agnostic.");
  }
  lines.push("");

  /* Non-negotiable tokens */
  lines.push("## 2. Non-negotiable design tokens");
  lines.push("Use these exact values. Do not substitute, round, or \"improve\" them.");
  lines.push("");
  const tokenLines = [];
  for (const row of palette.slice(0, 10)) {
    const { raw, cssVar } = splitTokenValue(row.value);
    tokenLines.push(`- \`${row.token}\`: \`${raw}\`${cssVar ? ` (source variable ${cssVar})` : ""}`);
  }
  lines.push(...tokenLines);

  if (font.familyStack) {
    lines.push(`- Font: \`${font.primaryFamily || font.familyStack}\` — full stack \`${font.familyStack}\`${font.size ? `, base ${font.size}/${font.lineHeight || "auto"}` : ""}${font.weight ? `, weight ${font.weight}` : ""}`);
  }
  const fontFaces = normalized.resources?.fontFaces || [];
  if (fontFaces.length > 0) {
    const families = new Map();
    for (const face of fontFaces) {
      if (!families.has(face.family)) families.set(face.family, new Set());
      families.get(face.family).add(face.weight);
    }
    lines.push(`- Self-host these font families (files listed in design-system.json): ${Array.from(families.entries()).slice(0, 4).map(([family, weights]) => `\`${family}\` (${Array.from(weights).join(", ")})`).join(", ")}`);
  }
  const base = inferSpacingBase(normalized.spacingScale);
  if (base) {
    lines.push(`- Spacing: snap **everything** to a ${base}px grid. Measured steps: ${(normalized.spacingScale || []).slice(0, 8).map((row) => splitTokenValue(row.value).raw).join(", ")}`);
  }
  if ((normalized.radiusTokens || []).length > 0) {
    lines.push(`- Radii: ${normalized.radiusTokens.map((row) => `\`${splitTokenValue(row.value).raw}\``).join(", ")} — never any other value.`);
  }
  if ((normalized.shadowTokens || []).length > 0) {
    lines.push(`- Shadows: ${normalized.shadowTokens.slice(0, 3).map((row) => `\`${splitTokenValue(row.value).raw}\``).join("; ")}`);
  }
  const ratio = estimateScaleRatio(normalized.typographyScale);
  if (ratio) {
    lines.push(`- Type scale ratio: ~${ratio} between steps (${(normalized.typographyScale || []).slice(0, 8).map((row) => splitTokenValue(row.value).raw).join(" → ")})`);
  }
  lines.push("");

  /* Page plan */
  lines.push("## 3. Build the page in this exact order");
  const structure = normalized.structure || [];
  if (structure.length > 0) {
    structure.forEach((block, index) => {
      const details = [];
      if (block.heading) details.push(`headline **"${block.heading}"**`);
      if (block.ctas.length > 0) details.push(`CTAs ${block.ctas.map((cta) => `"${cta}"`).join(" / ")}`);
      if (block.layout) details.push(`${block.layout}${block.columns > 1 ? `, ${block.columns} columns` : ""}`);
      if (block.imageCount > 0) details.push(`${block.imageCount} image(s)`);
      if (block.hasForm) details.push("a form (spec in section 6)");
      details.push(`background ${block.background}`);
      details.push(`vertical padding ${block.paddingY}`);
      details.push(`≈${block.height}px tall`);
      lines.push(`${index + 1}. **${block.role}** — ${details.join(", ")}.`);
    });
  } else {
    lines.push("Structure could not be measured; mirror the live page section by section using the screenshots.");
  }
  lines.push("");

  /* Headings */
  const headings = normalized.headings || [];
  if (headings.length > 0) {
    lines.push("## 4. Typography hierarchy (measured)");
    for (const h of headings) {
      lines.push(`- \`${h.level}\`: ${h.fontSize}/${h.lineHeight}, weight ${h.fontWeight}${h.letterSpacing !== "normal" ? `, letter-spacing ${h.letterSpacing}` : ""}${h.textTransform !== "none" ? `, ${h.textTransform}` : ""}, color \`${h.color}\`, margins ${h.marginTop}/${h.marginBottom}`);
    }
    lines.push("");
  }

  /* Components */
  lines.push("## 5. Components — copy these specs verbatim");
  const variants = normalized.buttonVariants || [];
  for (const variant of variants) {
    const s = variant.spec;
    lines.push("```css");
    lines.push(`/* button.${variant.name}${variant.example ? ` — e.g. "${variant.example}"` : ""} */`);
    lines.push(`background: ${s.background}; color: ${s.color}; border: ${s.border}; border-radius: ${s.borderRadius}; padding: ${s.padding}; font: ${s.fontWeight} ${s.fontSize};${s.boxShadow ? ` box-shadow: ${s.boxShadow};` : ""}${s.textTransform ? ` text-transform: ${s.textTransform};` : ""}`);
    lines.push("```");
  }
  const control = normalized.formControl;
  if (control) {
    lines.push(`- Inputs: height ${control.height}, padding ${control.padding}, border ${control.border}, radius ${control.borderRadius}, background \`${control.background}\`.`);
  }
  const link = normalized.linkSpec;
  if (link) {
    lines.push(`- Links: \`${link.color}\`, ${link.textDecoration || "none"}, weight ${link.fontWeight}.`);
  }
  const interactions = normalized.interactionStyles || [];
  if (interactions.length > 0) {
    lines.push(`- Reproduce these measured interaction states: ${interactions.slice(0, 5).map((rule) => `\`${rule.selector} { ${rule.declarations.join("; ")} }\``).join(" ; ")}`);
  }
  lines.push("");

  /* Forms */
  const forms = normalized.forms || [];
  if (forms.length > 0) {
    lines.push("## 6. Forms");
    for (const form of forms) {
      lines.push(`- \`${form.name}\` (${form.method.toUpperCase()}): ${form.fields.map((field) => `${field.label || field.placeholder || field.name || field.type} (${field.type}${field.required ? ", required" : ""})`).join(", ")}${form.submitText ? ` → submit "${form.submitText}"` : ""}`);
    }
    lines.push("");
  }

  /* Motion */
  lines.push(`## ${forms.length > 0 ? 7 : 6}. Motion script`);
  const motionItems = [];
  for (const keyframe of (normalized.keyframes || []).slice(0, 6)) {
    motionItems.push(`- \`@keyframes ${keyframe.name}\`: ${(keyframe.steps || []).slice(0, 3).join(" ")} (full steps in MOTION.md)`);
  }
  const meaningfulTriggers = (normalized.scrollTriggers || []).filter(
    (st) => st.trigger || Object.keys(st.animation || {}).length > 0
  );
  for (const st of meaningfulTriggers.slice(0, 5)) {
    const animation = Object.entries(st.animation || {})
      .slice(0, 3)
      .map(([key, value]) => `${key}:${value}`)
      .join(", ");
    motionItems.push(
      `- ScrollTrigger on \`${st.trigger || "?"}\`: start ${st.start}${st.scrub ? ", scrubbed to scroll" : ""}${st.pin ? ", pinned" : ""}${animation ? ` → ${animation}` : ""}`
    );
  }
  if (meaningfulTriggers.length > 5) {
    motionItems.push(`- ...and ${meaningfulTriggers.length - 5} more ScrollTriggers (full table in MOTION.md).`);
  }
  for (const layer of (normalized.parallax?.measured || []).slice(0, 3)) {
    motionItems.push(`- Parallax: \`${layer.selector}\` moves at ${layer.speedRatio}x scroll speed.`);
  }
  for (const lib of (normalized.animationLibs || []).slice(0, 6)) {
    motionItems.push(`- Uses ${lib.name} (${lib.evidence}) — install and configure it, or replicate its effect.`);
  }
  if (normalized.webgl?.webglCount > 0) {
    motionItems.push(`- ${normalized.webgl.webglCount} WebGL scene(s) — irreproducible from CSS: use an equivalent canvas scene, a video loop, or keyart of the same dimensions.`);
  }
  if (motionItems.length === 0) {
    motionItems.push("- The site is calm: transitions only. Keep them between the measured durations, no decorative animation.");
  }
  lines.push(...motionItems);
  const durations = (normalized.motionDurationTokens || []).slice(0, 4).map((row) => splitTokenValue(row.value).raw).join(", ");
  if (durations) {
    lines.push(`- All transition durations: ${durations}.`);
  }
  lines.push("");

  /* Responsive + a11y */
  lines.push("## Responsive & accessibility");
  const breakpoints = (normalized.breakpoints || []).map((item) => `${item.px}px`).join(", ");
  if (breakpoints) {
    lines.push(`- Breakpoints, exactly: ${breakpoints}. Below the smallest, stack columns and collapse navigation into a disclosure menu.`);
  }
  const a11y = normalized.a11y;
  if (a11y && a11y.contrastChecked > 0) {
    lines.push(`- Beat the source: it currently fails contrast on ${a11y.contrastFailures}/${a11y.contrastChecked} text samples and has ${a11y.smallTargets}/${a11y.targetsChecked} touch targets under 24px. Match the look, fix the failures.`);
  }
  lines.push("- Keyboard-first: every interactive element needs a visible focus-visible state.");
  lines.push("");

  /* Assets */
  const images = normalized.imageInventory || [];
  const logo = images.find((img) => img.role === "logo");
  const hero = images.find((img) => img.role === "hero");
  if (logo || hero || images.length > 0) {
    lines.push("## Assets");
    if (logo) lines.push(`- Logo: \`${logo.src}\` (${logo.width}x${logo.height})`);
    if (hero) lines.push(`- Hero visual: \`${hero.src}\` (${hero.width}x${hero.height})`);
    lines.push(`- Full inventory (${images.length} images with roles and dimensions) in design-system.json; the site clone ZIP contains every downloaded file.`);
    lines.push("");
  }

  /* Method + definition of done */
  lines.push("## Working method");
  lines.push("1. Set up the tokens first (CSS custom properties or the provided tailwind.config.js).");
  lines.push("2. Build the page skeleton in the section order above, desktop-first at the largest breakpoint.");
  lines.push("3. Style components with the verbatim specs, then wire every measured interaction state.");
  lines.push("4. Add the motion script last, one effect at a time.");
  lines.push("5. Compare against the screenshots after every section — fix drift immediately, never at the end.");
  lines.push("");
  lines.push("## Definition of done");
  lines.push("- [ ] Side-by-side with the source at every breakpoint: no unexplained difference in color, spacing, type, or radius.");
  lines.push("- [ ] Every color on the page appears in the token list above — zero invented values.");
  lines.push(`- [ ] The spacing grid (${base ? `${base}px` : "measured"}) holds everywhere.`);
  lines.push("- [ ] All measured hover/focus states behave identically.");
  lines.push("- [ ] Motion timing matches (play them side by side).");
  lines.push(`- [ ] Design health ≥ ${score}/100 on re-extraction (the source's own measured score).`);
  lines.push("");
  lines.push("**Companion files** (from the same extraction, use when you need more depth): DESIGN.md (full blueprint), MOTION.md (complete animation report), design-system.json (every token machine-readable), SKILL.md (agent skill), the site clone ZIP (HTML/CSS/fonts/images) and screenshots.");
  lines.push("");

  return lines.join("\n");
}

function recommendStackLine(stackNames) {
  const names = stackNames.map((name) => name.toLowerCase());
  if (names.some((name) => name.includes("next"))) {
    return "Rebuild with Next.js + Tailwind using the provided tailwind.config.js.";
  }
  if (names.some((name) => name.includes("react") || name.includes("framer"))) {
    return "Rebuild with React (+ Framer Motion if motion is listed below) and the provided tokens.";
  }
  if (names.some((name) => name.includes("vue") || name.includes("nuxt"))) {
    return "Rebuild with Vue/Nuxt and the provided tokens.";
  }
  if (names.some((name) => name.includes("wordpress") || name.includes("shopify") || name.includes("webflow") || name.includes("wix"))) {
    return "The source is a site builder: rebuild with any modern component stack; fidelity comes from the tokens, not the platform.";
  }
  return "Match the source stack for maximum fidelity, or use your standard stack with the tokens below.";
}

function inferName(title) {
  if (!title) {
    return "Extracted Site";
  }
  return title.replace(/\s*\|\s*.*/g, "").replace(/\s*-\s*.*/g, "").trim() || "Extracted Site";
}
